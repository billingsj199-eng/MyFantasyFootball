#!/usr/bin/env python3
"""Concatenate the small stable lookup-table data scripts into bundles.

Outputs:
    data/_bundle_lookups.js — boot bundle, replaces the individual script tags
        in index.html (36 files).
    data/_bundle_bbm.js — BBM tournament tables (6 bbm_* files), lazy-loaded via
        window._ensureBbmData() only when the My Teams construction-score path
        runs. Split out 2026-08-04 so the ~280 KB of BBM data stops shipping on
        every cold load.

Re-run this script whenever one of the bundled files is edited by hand. The
pipeline-regenerated files (d.js, all_players.js, weekly_stats_active.js, etc.)
are NOT in these lists — they keep loading as separate script tags so the
pipeline doesn't need to know about bundling.

Usage:
    python scripts/bundle_lookups.py
"""
from pathlib import Path
import sys

# Order matches the order these scripts currently load in index.html (lines 3351-3392).
# If you reorder, edit both this list AND the script tag in index.html in lockstep.
