# BBM tournament tables — consumed ONLY by the My Teams / construction-score code
# in app.js (_udComputeRosterConstruction + helpers, all typeof-guarded). Loaded
# lazily via window._ensureBbmData() in index.html.
BBM_FILES = [
    "bbm_first_pos_by_round.js",
    "bbm_pick_by_rank_round.js",
    "bbm_path_optimal.js",
    "bbm_optimizer_data.js",
    "bbm_stack_comp_multistage.js",
    "bbm_structural_multistage.js",
]

OUT = "_bundle_lookups.js"
OUT_BBM = "_bundle_bbm.js"


def _write_bundle(data_dir: Path, out_name: str, files: list[str], label: str) -> None:
    parts: list[str] = [
        "/* AUTO-GENERATED by scripts/bundle_lookups.py — do not edit by hand.",
        f"   Concatenation of {len(files)} {label}, in load order.",
        "   Edit a source file then re-run the script to refresh this bundle. */",
        "",
    ]
    total_bytes = 0
    for name in files:
        path = data_dir / name
        content = path.read_text(encoding="utf-8")
        total_bytes += len(content.encode("utf-8"))
        parts.append(f"// ===== {name} =====")
        # Ensure each file ends with a newline + statement terminator so the
        # next file's top-level statement can't accidentally chain onto the
        # previous file's last expression.
        if not content.endswith("\n"):
            content += "\n"
        parts.append(content)
        parts.append(";")  # belt-and-suspenders statement separator
        parts.append("")

    out_path = data_dir / out_name
    out_path.write_text("\n".join(parts), encoding="utf-8")
    out_bytes = out_path.stat().st_size
    print(f"Wrote {out_path} ({out_bytes:,} bytes, sum of inputs: {total_bytes:,} bytes)")


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    data_dir = root / "data"
    missing = [f for f in BUNDLED_FILES + BBM_FILES if not (data_dir / f).exists()]
    if missing:
        print(f"ERROR: missing files: {missing}", file=sys.stderr)
        return 1

    _write_bundle(data_dir, OUT, BUNDLED_FILES, "stable lookup tables")
    _write_bundle(data_dir, OUT_BBM, BBM_FILES,
                  "BBM tournament tables (lazy — window._ensureBbmData)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
