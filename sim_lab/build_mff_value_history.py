#!/usr/bin/env python3
"""
build_mff_value_history.py — MFF VALUE history for the player card's DYNASTY chart.
(Jack 2026-10-10: "make the card change all three" — MFF VALUE is the card's headline
value; its chart needs history.)

Source: the forward tracker's daily snapshots (sim_lab/_dyn_cache/mff_tracker/<date>_<fmt>.json,
written by `mff_tracker.py snapshot` in the 9am job; weekly backfill 2026-09-07..09-28).
Each snapshot = the FAIR / MFF VALUE order for KTC's top 200 (BALANCED, PPR) priced on
KTC's value scale. Per player and date: [value, overall rank, positional rank] within
that snapshot's pool (players only, by value). The card appends today's live board value
as the last point.

Output: <site>/data/mff_value_history.js
  window.MFF_VALUE_HISTORY = {dates: [...], src: {date: 'live'|'backfill'},
                              p: {"Name|POS": {"1qb": [[v, ovr, pos] | null, ...], "sf": [...]}}}
--site <repo> also bumps <meta name="mff-mffv-hist-v"> in index.html when the file changed.
numpy-free (the 9am job's scheduler Python has no numpy).
Usage: python build_mff_value_history.py --site "E:\\MyFantasyFootball\\MyFantasyFootball Files"
"""
import argparse
import datetime as dt
import glob
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SNAP = os.path.join(HERE, '_dyn_cache', 'mff_tracker')
FMTS = ('1qb', 'sf')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--site', required=True)
    args = ap.parse_args()
    snaps = {}
    for fp in glob.glob(os.path.join(SNAP, '*_*.json')):
        m = re.match(r'^(\d{4}-\d{2}-\d{2})_(1qb|sf)\.json$', os.path.basename(fp))
        if not m:
            continue
        d = json.load(open(fp, encoding='utf-8'))
        snaps.setdefault(m.group(1), {})[m.group(2)] = d
    dates = sorted(snaps)
    p, src = {}, {}
    for j, day in enumerate(dates):
        for fmt in FMTS:
            d = snaps[day].get(fmt)
            if not d:
                continue
            src[day] = 'backfill' if 'backfill' in str(d.get('src', '')) else 'live'
            rows = sorted((r for r in d.get('rows', []) if r.get('fair')), key=lambda r: -r['fair'])
            pc = {}
            for i, r in enumerate(rows):
                pc[r['pos']] = pc.get(r['pos'], 0) + 1
                rec = p.setdefault(r['n'] + '|' + r['pos'], {})
                arr = rec.setdefault(fmt, [None] * len(dates))
                arr[j] = [int(round(r['fair'])), i + 1, pc[r['pos']]]
    out = {'built': dt.datetime.now().strftime('%Y-%m-%d %H:%M'), 'dates': dates, 'src': src, 'p': p,
           'note': 'MFF VALUE (BALANCED, PPR) per tracker snapshot; pool = KTC top 200; ranks within the snapshot (players only)'}
    path = os.path.join(args.site, 'data', 'mff_value_history.js')
    body = ('// Auto-generated by sim_lab/build_mff_value_history.py — do not hand-edit.\n'
            '// MFF VALUE history for the player card DYNASTY chart (tracker snapshots).\n'
            'window.MFF_VALUE_HISTORY = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else ''
    # compare without the 'built' stamp so an unchanged history doesn't churn the file
    strip = lambda s: re.sub(r'"built":"[^"]*",', '', s)
    if strip(old) == strip(body):
        print(f'mff value history unchanged ({len(dates)} dates, {len(p)} players)')
        return
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(body)
    idx = os.path.join(args.site, 'index.html')
    html = open(idx, encoding='utf-8').read()
    stamp = dt.date.today().isoformat()
    new = re.sub(r'(<meta name="mff-mffv-hist-v" content=")[^"]*(")', r'\g<1>' + stamp + r'\g<2>', html)
    if new != html:
        with open(idx, 'w', encoding='utf-8', newline='') as f:
            f.write(new)
    print(f'wrote {path}: {len(dates)} dates, {len(p)} players, {os.path.getsize(path) // 1024} KB'
          + ('' if new != html or 'mff-mffv-hist-v' in html else ' (meta tag missing in index.html)'))


if __name__ == '__main__':
    main()
